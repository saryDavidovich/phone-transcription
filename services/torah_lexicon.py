def _words(block):
    return [w.replace('_', ' ') for w in block.split() if w and '...' not in w]


def glossary(full=True):
    """רשימת מונחים לפרומפט (מחרוזת אחת). full=False - רק ראשי תיבות ושמות שכיחים (מסלול "מעורב")."""
    if not full:
        groups = [_words(TERMS)[:60], _words(RISHONIM_ACHARONIM)[:25]]
    else:
        groups = [_words(TRACTATES), _words(TANACH), _words(TANNAIM_AMORAIM), _words(RISHONIM_ACHARONIM),
                  _words(ARAMAIC), _words(TERMS)]
    seen, out = set(), []
    for g in groups:
        for w in g:
            if w not in seen:
                seen.add(w)
                out.append(w)
    return ', '.join(out)


def vocab_list(limit=100):
    """לרשימת המונחים של המודל הייעודי של Google (עד 100)."""
    out = []
    for w in _words(RISHONIM_ACHARONIM) + _words(TANNAIM_AMORAIM) + _words(TRACTATES):
        if w not in out:
            out.append(w)
        if len(out) >= limit:
            break
    return out


